export function createT(lang) {
  const dict = STRINGS[lang] ?? STRINGS.en;
  const t = (key, vars = {}) => {
    const value = dict[key];
    if (value === undefined) return key;
    return typeof value === 'function' ? value(vars) : value;
  };
  t.lang = lang;
  const fmt = new Map();
  t.num = (n, digits = 0) => {
    if (!fmt.has(digits)) fmt.set(digits, new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits }));
    return fmt.get(digits).format(n).replace('-', '−');
  };
  t.signed = (n, digits = 1) => `${n >= 0 ? '+' : '−'}${t.num(Math.abs(n), digits)}`;
  t.minus = (n) => `−${n}`;
  const dateFmt = new Intl.DateTimeFormat(lang, { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
  t.date = (iso) => dateFmt.format(new Date(iso));
  const exactFmt = new Intl.NumberFormat(lang, { maximumFractionDigits: 2 });
  /** Up to two decimals, none when the value is whole: 37.5, 18.75, 100. */
  t.exact = (n) => exactFmt.format(n);
  t.short = (iso) => new Intl.DateTimeFormat(lang, { month: 'short', day: 'numeric' }).format(new Date(iso));
  t.day = (iso) => new Intl.DateTimeFormat(lang, { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' }).format(new Date(iso));
  return t;
}
